test('Gmail errors stay in the dialog without moving toolbar controls or the table', async ({ page, app }, info) => {
  const message = 'Gmail integration is not configured. Please contact an administrator.'
  await page.route('**/api/crm/gmail/connect', route => route.fulfill({ status: 503, json: { error: message } }))
  for (const width of [1440, 1180, 390]) {
    await page.setViewportSize({ width, height: 960 })
    await page.goto('/dashboard/crm')
    // Measure layout independently of the existing page entrance/button hover motion.
    await page.addStyleTag({ content: '* { animation: none !important; transition: none !important; }' })
    await page.mouse.move(0, 0)
    const button = page.getByRole('button', { name: 'Connect Gmail', exact: true })
    await expect(button).toBeEnabled()
    const positions = () => page.locator('.crm-toolbar, .crm-toolbar > *, .crm-gmail-button, .crm-page > .table-card').evaluateAll(elements => elements.map(element => { const { x, y, width, height } = element.getBoundingClientRect(); return { x, y, width, height } }))
    const before = await positions()
    await button.click()
    const dialog = page.getByRole('dialog', { name: 'Gmail Connection' })
    await expect(dialog.getByRole('alert')).toHaveText(message)
    await dialog.locator('.modal-footer').getByRole('button', { name: 'Close', exact: true }).click()
    await expect(dialog).toHaveCount(0)
    await page.mouse.move(0, 0)
    expect(await positions()).toEqual(before)
    await expect(page.locator('.crm-toolbar').getByRole('alert')).toHaveCount(0)
    await button.click()
    await expect(dialog.getByRole('alert')).toHaveText(message)
    await page.keyboard.press('Escape')
    await page.mouse.move(0, 0)
    expect(await positions()).toEqual(before)
    if (width === 1440 && info.project.name === 'chromium') await page.screenshot({ path: 'outputs/crm-gmail-verification/error-layout.png', animations: 'disabled' })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
  }
  expect(app.consoleErrors).toEqual([])
})
test('manual Gmail sync starts immediately, disables repeat clicks and puts a real processed email in Activity History', async ({ page, gmailCrm, app }, info) => {
  await gmailCrm.post('/api/crm', { organisation_name: 'Manual Sync Client', contacts: [{ name: 'HR', email: 'hr@client.test', mobile: '9876543210' }] })
  await page.goto('/dashboard/crm')
  await expect(page.getByRole('button', { name: 'Sync Gmail now' })).toHaveCount(0)
  await gmailCrm.post('/test/gmail'); await page.reload()
  const sync = page.locator('.crm-toolbar').getByRole('button', { name: 'Sync Gmail now' })
  await expect(sync).toBeEnabled()
  let release
  const gate = new Promise(resolve => { release = resolve })
  let requests = 0
  await page.route('**/api/crm/gmail/sync', async route => { requests++; await gate; await route.fallback() })
  await sync.click()
  await expect(sync).toHaveText('Syncing...'); await expect(sync).toBeDisabled()
  await expect(page.locator('.crm-toolbar').getByRole('button', { name: 'Disconnect Gmail', exact: true })).toBeDisabled()
  await expect.poll(() => requests).toBe(1)
  release()
  const dialog = page.getByRole('dialog', { name: 'Gmail Connection' })
  await expect(dialog.getByRole('status')).toContainText('Gmail sync complete')
  await expect(dialog).toContainText('Last successful synchronisation:')
  if (info.project.name === 'chromium') await page.screenshot({ path: 'outputs/crm-gmail-verification/manual-sync.png', animations: 'disabled' })
  await page.keyboard.press('Escape')
  await sync.click()
  await expect(dialog.getByRole('alert')).toContainText('30 seconds')
  await page.keyboard.press('Escape')
  await page.locator('.crm-table tbody tr').filter({ hasText: 'Manual Sync Client' }).getByRole('button', { name: 'Activity History', exact: true }).click()
  const history = page.getByRole('dialog', { name: 'Activity History' })
  await expect(history).toContainText('Manual sync meeting')
  await expect(history.locator('.crm-history-entry').filter({ hasText: 'Incoming email' })).toHaveCount(1)
  await page.keyboard.press('Escape')
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(sync).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
  expect(app.consoleErrors).toEqual([])
})
