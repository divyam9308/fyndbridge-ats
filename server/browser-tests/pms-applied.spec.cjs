test('PMS idle settles; cold, repeated, mouse, keyboard and edited-field navigation use normal links', async ({ page, app }, testInfo) => {
  // Force the destination to be genuinely cold, including a pending chunk load.
  await page.route('**/src/pages/AppliedCandidatesPage.jsx*', async route => { await new Promise(resolve => setTimeout(resolve, 350)); await route.continue() })
  await page.goto(performanceUrl)
  await expect(page.locator('.performance-input.is-self_score').first()).toBeEnabled()
  await expect(page.locator('.performance-employee-select > button')).toContainText('Test Recruiter')
  await page.waitForTimeout(600)
  const before = await page.evaluate(() => window.__reactCommits)
  await page.waitForTimeout(1200)
  const idleCommits = await page.evaluate(start => window.__reactCommits - start, before)
  expect(idleCommits).toBeLessThan(3)
  const start = Date.now()
  await page.locator('#nav-applied-candidates').click()
  await expect(page.getByRole('table', { name: 'Applied Candidates', exact: true })).toBeVisible()
  const coldNavigationMs = Date.now() - start
  await expect(page.locator('.performance-page')).toHaveCount(0)
  for (let i = 0; i < 3; i++) {
    await page.locator('#nav-pms').click()
    await expect(page.locator('.performance-input.is-self_score').first()).toBeEnabled()
    await page.locator('.performance-input.is-self_score').first().fill('4')
    await page.locator('#nav-applied-candidates').focus()
    await page.keyboard.press('Enter')
    await expect(page.getByRole('table', { name: 'Applied Candidates', exact: true })).toBeVisible()
  }
  expect(app.consoleErrors).toEqual([])
  if (testInfo.project.name === 'chromium') {
    await fs.writeFile(path.join(evidenceDir, 'pms-navigation-metrics.json'), JSON.stringify({ idleIntervalMs: 1200, idleCommits, coldModuleDelayMs: 350, coldNavigationMs, repeatedNavigations: 3, pointerWorkaroundPresent: false }, null, 2))
    await page.screenshot({ path: path.join(evidenceDir, 'pms-navigation-completed.png') })
  }
})

