const { test, expect } = require('./fixtures.cjs')
const { employmentDatabase, STAFF_IDS } = require('../test-support/employmentMemory.cjs')

test('team attendance replaces Total Hours with dashboard activity averages and follows quarter selection', async ({ page, app }) => {
  app.employmentDb = employmentDatabase()
  app.employmentDb.activitySummaries.set(STAFF_IDS.active, { average_seconds: 12000, average_days: 4 })
  await page.goto('/dashboard/attendance')
  await page.getByRole('button', { name: 'Team Attendance', exact: true }).click()
  const table = page.locator('.att-table-card')
  await expect(table.getByRole('columnheader', { name: 'Average Active Time' })).toBeVisible()
  await expect(table.getByRole('columnheader', { name: 'Total Hours', exact: true })).toHaveCount(0)
  const active = table.getByRole('row').filter({ hasText: 'Active Consultant' })
  await expect(active.getByRole('cell').nth(6)).toHaveText('3h 20m')
  await expect(table.getByRole('row').filter({ hasText: 'On Leave Consultant' }).getByRole('cell').nth(6)).toHaveText('0m')
  await page.getByRole('combobox', { name: 'Financial Year', exact: true }).selectOption('FY 2026-27')
  await page.getByRole('combobox', { name: 'Month', exact: true }).selectOption('2027-0')
  await expect(active.getByRole('cell').nth(6)).toHaveAttribute('title', 'FY 2026-27 Q4')
  await expect.poll(() => app.employmentDb.operations.some(operation => operation.kind === 'rpc' && operation.args.p_start === '2027-01-01' && operation.args.p_end === '2027-03-31')).toBe(true)
  expect(app.consoleErrors).toEqual([])
})
