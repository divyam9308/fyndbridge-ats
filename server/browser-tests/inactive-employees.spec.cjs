const { test, expect, evidenceDir } = require('./fixtures.cjs')
const { employmentDatabase, STAFF_IDS } = require('../test-support/employmentMemory.cjs')
const { localDate, getFinancialYearForDate } = require('../src/services/attendanceUtils')
const path = require('node:path')

const today = localDate()
const year = Number(today.slice(0, 4)), month = Number(today.slice(5, 7))
const employeeSelector = page => page.locator('.performance-employee-select > button')

test.beforeEach(async ({ app }) => { app.employmentDb = employmentDatabase(today) })

test('team excludes inactive employees now and in future; history retains attendance and stops absences after departure', async ({ page, app }, testInfo) => {
  const records = structuredClone(app.employmentDb.tables.attendance_records)
  await page.goto('/dashboard/attendance')
  await page.getByRole('button', { name: 'Team Attendance', exact: true }).click()
  const table = page.locator('.att-table-card')
  await expect(table).toContainText('Active Consultant')
  await expect(table).toContainText('On Leave Consultant')
  await expect(table).not.toContainText('Former Consultant')
  await expect(page.getByRole('combobox', { name: 'Employee', exact: true })).not.toContainText('Former Consultant')
  await page.getByRole('checkbox', { name: 'Show past employees', exact: true }).check()
  await expect(table).toContainText('Former Consultant')
  const formerRow = table.getByRole('row').filter({ hasText: 'Former Consultant' })
  await expect(formerRow.getByRole('cell').nth(2)).toHaveText('1')
  await formerRow.getByRole('button', { name: 'Former Consultant' }).click()
  await expect(page.getByRole('heading', { name: 'Former Consultant · Attendance' })).toBeVisible()
  await expect(page.locator('.att-modal')).toContainText('Inactive')
  await expect(page.locator('.att-modal')).toContainText('Present')
  if (testInfo.project.name === 'webkit') await page.screenshot({ path: path.join(evidenceDir, 'attendance-former-history.png') })
  await page.locator('.att-modal > header button').click()
  const next = new Date(Date.UTC(year, month, 1))
  if (getFinancialYearForDate(next) !== getFinancialYearForDate(today)) await page.getByRole('combobox', { name: 'Financial Year', exact: true }).selectOption(getFinancialYearForDate(next))
  await page.getByRole('combobox', { name: 'Month', exact: true }).selectOption(`${next.getUTCFullYear()}-${next.getUTCMonth()}`)
  await expect(table).toContainText('Active Consultant')
  await expect(table).not.toContainText('Former Consultant')
  const previous = new Date(Date.UTC(year, month - 2, 1))
  if (getFinancialYearForDate(previous) !== getFinancialYearForDate(next)) await page.getByRole('combobox', { name: 'Financial Year', exact: true }).selectOption(getFinancialYearForDate(previous))
  await page.getByRole('combobox', { name: 'Month', exact: true }).selectOption(`${previous.getUTCFullYear()}-${previous.getUTCMonth()}`)
  await page.getByRole('checkbox', { name: 'Show past employees', exact: true }).uncheck()
  await expect(table).toContainText('Former Consultant')
  expect(app.employmentDb.tables.attendance_records).toEqual(records)
  expect(app.consoleErrors).toEqual([])
})

test('leave balance hides inactive staff, keeps their history read-only and refreshes after a status change', async ({ page, app }, testInfo) => {
  await page.goto('/dashboard/attendance')
  await page.getByRole('button', { name: 'Leave Balance', exact: true }).click()
  const table = page.locator('.att-table-card')
  await expect(table).toContainText('Active Consultant')
  await expect(table).not.toContainText('Former Consultant')
  await page.getByRole('checkbox', { name: 'Show past employees', exact: true }).check()
  const historical = table.getByRole('row').filter({ hasText: 'Former Consultant' })
  await expect(historical.getByRole('button', { name: 'Past employee', exact: true })).toBeDisabled()
  const adjustment = await page.evaluate(async userId => {
    return (await fetch(`/api/attendance/leave-balances/${userId}/adjust`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ amount: 10 }) })).status
  }, STAFF_IDS.former)
  expect(adjustment).toBe(409)
  if (testInfo.project.name === 'webkit') await page.screenshot({ path: path.join(evidenceDir, 'leave-balance-former-history.png') })
  await page.getByRole('checkbox', { name: 'Show past employees', exact: true }).uncheck()
  const status = app.employmentDb.tables.employee_statuses.find(row => row.user_id === STAFF_IDS.active)
  status.status = 'inactive'
  app.emitEmploymentStatus(status)
  await expect(table).not.toContainText('Active Consultant')
  await expect(table).toContainText('On Leave Consultant')
  expect(app.consoleErrors).toEqual([])
})

test('PMS hides inactive employees, reads saved history without generating quarters, and blocks updates through the API', async ({ page, app }, testInfo) => {
  const originalRows = structuredClone(app.employmentDb.tables.performance_review_rows)
  await page.goto('/dashboard/performance')
  await expect(page.locator('.performance-input.is-self_score').first()).toBeEnabled()
  await employeeSelector(page).click()
  await expect(page.getByRole('button', { name: /^Active Consultant/ })).toBeVisible()
  await expect(page.getByRole('button', { name: /^Former Consultant/ })).toHaveCount(0)
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: /^Q1/ }).click()
  await page.getByRole('checkbox', { name: 'Show past employees with saved reviews' }).check()
  await employeeSelector(page).click()
  await page.getByRole('button', { name: /^Former Consultant/ }).click()
  await expect(page.getByRole('status')).toContainText('Past employee review · Read only')
  await expect(page.locator('.performance-input.is-self_score').first()).toHaveValue('4')
  await expect(page.locator('.performance-input.is-self_score').first()).toBeDisabled()
  await expect(page.locator('.performance-input.is-work_done').first()).toHaveValue('Saved before departure')
  const storedQuarters = () => app.employmentDb.tables.performance_reviews.filter(row => row.employee_user_id === STAFF_IDS.former).map(row => row.review_period)
  expect(storedQuarters()).toEqual(['Q1'])
  await page.waitForTimeout(350)
  expect(storedQuarters()).toEqual(['Q1'])
  const result = await page.evaluate(async userId => {
    const response = await fetch(`/api/performance/${userId}`, { method: 'PUT', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ period: 'Q4', rows: [] }) })
    return response.status
  }, STAFF_IDS.former)
  expect(result).toBe(409)
  expect(app.employmentDb.tables.performance_review_rows.filter(row => row.review_id === 'old-review')).toEqual(originalRows)
  if (testInfo.project.name === 'webkit') await page.screenshot({ path: path.join(evidenceDir, 'pms-former-read-only.png') })
  await page.getByRole('button', { name: /^Q4/ }).click()
  await expect(employeeSelector(page)).toContainText('Test Recruiter')
  await employeeSelector(page).click()
  await expect(page.getByRole('button', { name: /^Former Consultant/ })).toHaveCount(0)
  await expect(page.getByRole('button', { name: /^Former Without Reviews/ })).toHaveCount(0)
  await page.keyboard.press('Escape')
  await page.getByRole('checkbox', { name: 'Show past employees with saved reviews' }).uncheck()
  const status = app.employmentDb.tables.employee_statuses.find(row => row.user_id === STAFF_IDS.former)
  status.status = 'active'
  app.emitEmploymentStatus(status)
  await expect(employeeSelector(page)).toContainText('Former Consultant')
  await employeeSelector(page).click()
  await page.locator('.performance-employee-menu').getByRole('button', { name: /^Former Consultant/ }).click()
  await expect(page.locator('.performance-input.is-self_score').first()).toBeEnabled()
  expect(app.consoleErrors).toEqual([])
})

test('selected PMS employee disappears immediately on inactivation and the page settles without a render loop', async ({ page, app }) => {
  await page.goto('/dashboard/performance')
  await expect(page.locator('.performance-input.is-self_score').first()).toBeEnabled()
  await employeeSelector(page).click()
  await page.locator('.performance-employee-menu').getByRole('button', { name: /^Active Consultant/ }).click()
  await expect(employeeSelector(page)).toContainText('Active Consultant')
  const status = app.employmentDb.tables.employee_statuses.find(row => row.user_id === STAFF_IDS.active)
  status.status = 'inactive'
  status.updated_at = new Date().toISOString()
  app.emitEmploymentStatus(status)
  await expect(employeeSelector(page)).toContainText('Test Recruiter')
  await employeeSelector(page).click()
  await expect(page.locator('.performance-employee-menu')).not.toContainText('Active Consultant')
  await page.keyboard.press('Escape')
  await page.waitForTimeout(500)
  const before = await page.evaluate(() => window.__reactCommits)
  await page.waitForTimeout(800)
  expect(await page.evaluate(start => window.__reactCommits - start, before)).toBeLessThan(3)
  expect(app.consoleErrors).toEqual([])
})
