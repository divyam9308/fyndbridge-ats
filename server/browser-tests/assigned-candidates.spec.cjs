test('UI safety: responsive page and centered wizard preserve horizontal geometry on open and close',async({page},info)=>{
  await goto(page)
  await expect(row(page,'Test Candidate 301')).toBeVisible()
  await page.evaluate(()=>document.fonts.ready)
  const measurements=[]
  for(const width of [1440,1280,1024,768]){
    await page.setViewportSize({width,height:800})
    const before=await page.locator('.assigned-page').evaluate(node=>({x:node.getBoundingClientRect().x,width:node.getBoundingClientRect().width,documentWidth:document.documentElement.scrollWidth,viewport:innerWidth}))
    await page.getByRole('button',{name:'New',exact:true}).click()
    const dialog=details(page);await expect(dialog).toBeVisible()
    const bounds=await dialog.boundingBox()
    const during=await page.locator('.assigned-page').evaluate(node=>({x:node.getBoundingClientRect().x,width:node.getBoundingClientRect().width}))
    await dialog.getByRole('button',{name:'Cancel',exact:true}).click()
    const after=await page.locator('.assigned-page').evaluate(node=>({x:node.getBoundingClientRect().x,width:node.getBoundingClientRect().width}))
    measurements.push({width,before,during,after,dialog:bounds})
  }
  await fs.writeFile(info.outputPath('assigned-popup-geometry.json'),JSON.stringify(measurements,null,2))
  for(const item of measurements){
    expect(item.before.documentWidth).toBeLessThanOrEqual(item.width+1)
    expect(item.dialog.x+item.dialog.width/2).toBeCloseTo(item.width/2,0)
    expect(item.during.x).toBeCloseTo(item.before.x,1);expect(item.during.width).toBeCloseTo(item.before.width,1)
    expect(item.after.x).toBeCloseTo(item.before.x,1);expect(item.after.width).toBeCloseTo(item.before.width,1)
  }
})

