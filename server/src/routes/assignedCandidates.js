const express = require('express')
const { requirePageViewPermission } = require('../middleware/pageViewAccessMiddleware')
const { upload, handleUploadErrors } = require('../middleware/uploadMiddleware')
const controller = require('../controllers/assignedCandidatesController')
const { isUuid } = require('../services/assignedCandidates')
const router = express.Router()
router.use(requirePageViewPermission('assigned_candidates'))
router.use((req,res,next)=>{res.setHeader('Cache-Control','private, no-store');next()})
router.param('id',(req,res,next,id)=>isUuid(id)?next():res.status(404).json({error:'Assignment not found.'}))
router.get('/',controller.list)
router.get('/count',controller.count)
router.post('/',controller.create)
router.post('/uploads',upload.single('cv_file'),handleUploadErrors,controller.upload)
router.post('/uploads/discard',controller.discard)
router.post('/delete',controller.remove)
router.patch('/:id/status',controller.status)
router.patch('/:id/consultant',controller.reassign)
router.get('/:id/cv',controller.cv)
router.post('/:id/parse',requirePageViewPermission('candidates'),controller.parse)
router.post('/:id/transfer',requirePageViewPermission('candidates'),controller.transfer)
router.delete('/:id',controller.remove)
router.use((err,req,res,next)=>{if(res.headersSent)return next(err);console.error('assigned candidates route:',err.message);res.status(500).json({error:'Unable to complete this request.'})})
module.exports=router
